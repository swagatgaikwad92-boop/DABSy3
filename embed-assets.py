# Regenerates the root-level embedded copies of the artwork (run from the project root: python3 tools/embed-assets.py)
# magic-assets.js  : character layers + the first room (always loaded with Magic World)
# wp-<id>.js       : one per extra wallpaper, loaded ONLY if the image in assets/magic/ cannot be fetched
import base64, json
d = "assets/magic/"
b64 = lambda n: "data:image/webp;base64," + base64.b64encode(open(d + n, "rb").read()).decode()
core = ["room-night.webp", "dabsy-body.webp", "dabsy-eye-l.webp", "dabsy-eye-r.webp", "dabsy-bow.webp", "dabsy-halo.webp", "dabsy-flecks.webp"]
out = {n: b64(n) for n in core}
open("magic-assets.js", "w").write("/* magic-assets.js (generated by tools/embed-assets.py) */\n(function(){window.DABSy=window.DABSy||{};window.DABSy.worldAssets=Object.assign(window.DABSy.worldAssets||{}," + json.dumps(out) + ");})();\n")
for k in ["window-nook-day", "lakeside-night", "lakeside-day", "city-window-day"]:
    open("wp-%s.js" % k, "w").write('(function(){window.DABSy=window.DABSy||{};window.DABSy.worldAssets=window.DABSy.worldAssets||{};window.DABSy.worldAssets["%s.webp"]="%s";})();\n' % (k, b64(k + ".webp")))
